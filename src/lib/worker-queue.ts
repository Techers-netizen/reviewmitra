/**
 * File-based job queue between the Next.js app and the SeleniumBase worker.
 *
 * The dashboard's Post Reply button (Google + worker transport) does NOT call
 * Google directly. It writes a job JSON file into worker/jobs/, the Python
 * poller (worker/run_worker.py) picks it up, drives Chrome, and POSTs the
 * outcome back to /api/worker/jobs/[id]/result.
 *
 * A job is only ever "posted" in the DB when the worker verifies the reply
 * is visible on the Google Maps page. Anything else is "failed".
 */

import fs from "fs";
import path from "path";
import { db } from "@/lib/db";

export type WorkerJobType = "google_reply" | "google_list_reviews";
export type WorkerJobStatus =
  | "queued"
  | "processing"
  | "completed"
  | "failed";

export interface WorkerJob {
  id: string;
  type: WorkerJobType;
  businessId: string;
  reviewId: string | null;
  externalReviewId: string | null;
  reviewerName: string;
  reviewSnippet: string;
  replyText: string;
  businessUrl: string;
  dryRun: boolean;
  status: WorkerJobStatus;
  result: Record<string, unknown> | null;
  error: string | null;
  replyDbId: string | null;
  createdAt: string;
  updatedAt: string;
  startedAt?: string;
  finishedAt?: string;
  worker_stdout_tail?: string;
  worker_stderr_tail?: string;
}

export function jobsDir(): string {
  return path.join(process.cwd(), "worker", "jobs");
}

export function jobPath(jobId: string): string {
  // job ids are generated by us (job_<random>); strip any path separators.
  const safe = jobId.replace(/[^A-Za-z0-9_-]/g, "");
  return path.join(jobsDir(), `${safe}.json`);
}

export function enqueueWorkerJob(
  job: Omit<WorkerJob, "id" | "status" | "result" | "error" | "createdAt" | "updatedAt">
): WorkerJob {
  const dir = jobsDir();
  fs.mkdirSync(dir, { recursive: true });
  const now = new Date().toISOString();
  const full: WorkerJob = {
    ...job,
    id: `job_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 8)}`,
    status: "queued",
    result: null,
    error: null,
    createdAt: now,
    updatedAt: now,
  };
  fs.writeFileSync(jobPath(full.id), JSON.stringify(full, null, 2));
  return full;
}

export function readWorkerJob(jobId: string): WorkerJob | null {
  try {
    const raw = fs.readFileSync(jobPath(jobId), "utf-8");
    return JSON.parse(raw) as WorkerJob;
  } catch {
    return null;
  }
}

export function listWorkerJobs(limit = 20): WorkerJob[] {
  try {
    const dir = jobsDir();
    if (!fs.existsSync(dir)) return [];
    return fs
      .readdirSync(dir)
      .filter((f) => f.endsWith(".json"))
      .map((f) => {
        try {
          return JSON.parse(fs.readFileSync(path.join(dir, f), "utf-8")) as WorkerJob;
        } catch {
          return null;
        }
      })
      .filter((j): j is WorkerJob => j !== null)
      .sort((a, b) => (a.createdAt < b.createdAt ? 1 : -1))
      .slice(0, limit);
  } catch {
    return [];
  }
}

/** "worker" transport is enabled with GOOGLE_REPLY_TRANSPORT=worker. */
export function isWorkerTransportEnabled(): boolean {
  return process.env.GOOGLE_REPLY_TRANSPORT === "worker";
}

/**
 * The URL the SeleniumBase worker should open for a business.
 *
 * Share links (share.google/...) redirect to a mobile Google Search page
 * (client=ms-android-samsung-ss) that the worker cannot load, so for those
 * we use a direct Google Maps search URL instead. A stored non-share
 * googleReviewUrl (e.g. a maps/place link) is used as-is.
 */
export function workerBusinessUrl(business: {
  businessName: string;
  city?: string | null;
  googleReviewUrl?: string | null;
}): string {
  const stored = business.googleReviewUrl || "";
  if (stored && !stored.includes("share.google")) return stored;
  const query = [business.businessName, business.city].filter(Boolean).join(" ");
  return `https://www.google.com/maps/search/${encodeURIComponent(query)}`;
}

export interface WorkerJobOutcome {
  status?: string;
  success: boolean;
  verified: boolean;
  dryRun: boolean;
  error: string | null;
  detail: unknown;
}

/**
 * Apply a finished job's outcome to the linked ReviewReply row, honestly:
 * - dry run: the placeholder row is deleted (nothing was ever posted).
 * - completed + success + verified on the page: row -> "posted", review
 *   -> isReplied=true.
 * - anything else: row -> "failed".
 * Idempotent: a row that is no longer "queued" is left alone.
 * Returns what was applied ("no-db-row" | "not-finished" | "row-missing" |
 * "already-applied" | "dry-run-row-removed" | "marked-posted" |
 * "marked-failed").
 */
export async function applyJobOutcomeToDb(
  job: WorkerJob,
  outcome?: WorkerJobOutcome
): Promise<string> {
  // Nothing to apply: no linked DB row, or job not finished yet.
  if (!job.replyDbId) return "no-db-row";
  if (job.status !== "completed" && job.status !== "failed") return "not-finished";

  const row = await db.reviewReply.findUnique({ where: { id: job.replyDbId } });
  if (!row) return "row-missing";
  if (row.postStatus !== "queued") return "already-applied";

  const dryRun = outcome?.dryRun ?? job.dryRun;
  const success = outcome?.success ?? !!job.result?.ok;
  const verified =
    outcome?.verified ??
    (job.status === "completed" &&
      !dryRun &&
      !!(job.result as Record<string, unknown> | null)?.verified_on_page);

  if (dryRun) {
    // A dry run posts nothing: remove the placeholder row so the dashboard
    // never shows a reply that was never sent.
    await db.reviewReply.delete({ where: { id: job.replyDbId } });
    return "dry-run-row-removed";
  }
  if (job.status === "completed" && success && verified) {
    await db.reviewReply.update({
      where: { id: job.replyDbId },
      data: { postStatus: "posted" },
    });
    await db.review.update({
      where: { id: job.reviewId as string },
      data: { isReplied: true },
    });
    return "marked-posted";
  }
  // Any other finished state is a failure: record it honestly.
  await db.reviewReply.update({
    where: { id: job.replyDbId },
    data: { postStatus: "failed" },
  });
  return "marked-failed";
}
